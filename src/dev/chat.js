// DEV AI-AGENT CHATBOX — opened with F2. Part of the opt-in ?dev=1 harness.
// Human types issues here; the agent can also post findings (__dev.chat.issue()).
// Messages persist in localStorage. The agent-side CDP driver flushes them to
// fixNeeded.txt in the project root (see tools/agent-driver.mjs save-issues).
// A browser-only "Download" fallback saves the same file via a Blob.

const KEY = 'tlwo_dev_chat_v1'
let panel = null, logEl = null, inputEl = null
let messages = []

function now() { return new Date().toISOString() }
function load() {
  try { const v = JSON.parse(localStorage.getItem(KEY) || '[]'); if (Array.isArray(v)) messages = v } catch (e) { messages = [] }
}
function persist() { try { localStorage.setItem(KEY, JSON.stringify(messages.slice(-100))) } catch (e) {} }

function render() {
  if (!logEl) return
  logEl.innerHTML = ''
  for (const m of messages) {
    const row = document.createElement('div')
    row.style.cssText = `margin:0 0 6px;padding:5px 7px;border-left:3px solid ${m.kind === 'issue' ? '#e0a33a' : m.who === 'agent' ? '#5fa8e0' : '#6fbf73'};background:rgba(255,255,255,.05)`
    const head = document.createElement('div')
    head.style.cssText = 'font:10px monospace;opacity:.75;margin-bottom:2px'
    head.textContent = `${m.who === 'agent' ? 'AGENT' : 'YOU'}${m.kind === 'issue' ? ' · ISSUE' : ''} · ${m.t} · ${m.level || '-'}`
    const body = document.createElement('div')
    body.style.cssText = 'font:12px/1.4 system-ui,sans-serif;white-space:pre-wrap;word-break:break-word'
    body.textContent = m.text
    row.append(head, body); logEl.appendChild(row)
  }
  logEl.scrollTop = logEl.scrollHeight
}

function context() {
  try { const s = window.__dev && window.__dev.state(); return s ? { level: s.level, clock: s.clock, errors: s.errorCount } : {} } catch (e) { return {} }
}

function post({ who = 'human', text = '', kind = 'note', level } = {}) {
  const entry = { t: now(), who, kind, text: String(text).slice(0, 2000), level: level || context().level || null }
  messages.push(entry)
  if (messages.length > 100) messages.shift()
  persist(); render()
  window.dispatchEvent(new CustomEvent('dev-chat-message', { detail: entry }))
  return entry
}

function send() {
  const text = (inputEl && inputEl.value || '').trim()
  if (!text) return null
  if (inputEl) inputEl.value = ''
  post({ who: 'human', text, kind: 'issue' })
  toastSaved(`Issue queued (#${messages.length}). Run 'save-issues' to write fixNeeded.txt.`)
  return messages[messages.length - 1]
}

function toastSaved(msg) {
  const t = document.getElementById('toast')
  if (t) { t.textContent = msg; t.classList.add('show'); setTimeout(() => t.classList.remove('show'), 3500) }
}

function fileText() {
  const lines = ['# Fix Needed — THE LAST WAY OUT', '# Generated by DEV AI AGENT CHATBOX (F2)', `# Last updated: ${now()}`, `# Total entries: ${messages.length}`, '']
  messages.forEach((m, i) => {
    lines.push(`## [${i + 1}] ${m.t} — ${m.who === 'agent' ? 'AGENT' : 'HUMAN'}${m.kind === 'issue' ? ' / ISSUE' : ''}`)
    lines.push(`Level: ${m.level || 'unknown'}`)
    lines.push('')
    lines.push(m.text)
    lines.push('')
    lines.push('Status: OPEN')
    lines.push('')
  })
  return lines.join('\n')
}

function save() {
  const text = fileText()
  // Electron (if a privileged bridge was added): write straight to project root.
  if (window.electronAPI && typeof window.electronAPI.saveDevIssues === 'function') {
    try { window.electronAPI.saveDevIssues(text); toastSaved('Saved to fixNeeded.txt'); return 'electron-ipc' } catch (e) {}
  }
  // Browser fallback: download the same file.
  try {
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' })
    const a = document.createElement('a')
    a.href = URL.createObjectURL(blob); a.download = 'fixNeeded.txt'
    document.body.appendChild(a); a.click(); a.remove()
    setTimeout(() => URL.revokeObjectURL(a.href), 5000)
    toastSaved('Downloaded fixNeeded.txt')
    return 'download'
  } catch (e) { toastSaved('Save failed: ' + e.message); return 'error:' + e.message }
}

function analyze() {
  let rep = null
  try { rep = window.__dev && window.__dev.report() } catch (e) {}
  if (!rep) { post({ who: 'agent', text: 'No dev report available (open with ?dev=1).' }); return null }
  const bad = (rep.checks || []).filter(c => !c.ok).map(c => `${c.name}: ${c.detail}`)
  const errs = (rep.errors || []).slice(-3).map(e => `${e.type}: ${e.message || e.result || ''}`)
  const text = bad.length || errs.length
    ? `AUTO-TRIAGE found ${bad.length} failed check(s), ${errs.length} error(s).\n${bad.join('\n')}\n${errs.join('\n')}\nLevel: ${rep.state && rep.state.level}`
    : `AUTO-TRIAGE: no issues detected at ${rep.state && rep.state.level} (${(rep.checks || []).length} checks passed).`
  post({ who: 'agent', text, kind: bad.length || errs.length ? 'issue' : 'note' })
  return messages[messages.length - 1]
}

function toggle(force) {
  if (!panel) return false
  const show = force === undefined ? panel.classList.contains('hidden') : !!force
  panel.classList.toggle('hidden', !show)
  if (show && inputEl) setTimeout(() => inputEl.focus(), 30)
  return show
}

function makePanel() {
  panel = document.createElement('div')
  panel.id = 'dev-chat'
  panel.className = 'hidden'
  panel.style.cssText = 'position:fixed;right:10px;bottom:10px;z-index:100000;width:410px;max-height:64vh;display:flex;flex-direction:column;background:rgba(10,12,16,.94);border:1px solid #3a5a4a;color:#dfe8e0;border-radius:6px;box-shadow:0 8px 30px rgba(0,0,0,.6);font-family:system-ui,sans-serif'
  panel.innerHTML = `
    <div style="padding:7px 9px;background:#16231c;border-bottom:1px solid #3a5a4a;font:600 12px monospace;color:#9fe0a0;display:flex;justify-content:space-between">
      <span>DEV AGENT CHAT · F2</span><span id="dev-chat-count" style="opacity:.7"></span>
    </div>
    <div id="dev-chat-log" style="flex:1;overflow:auto;padding:8px;min-height:130px"></div>
    <div style="padding:6px 8px;border-top:1px solid #2a3a30;display:flex;gap:5px">
      <input id="dev-chat-input" placeholder="Type an issue and press Enter…" style="flex:1;background:#0d1410;border:1px solid #33503f;color:#fff;padding:6px;border-radius:4px;font:12px system-ui">
      <button id="dev-chat-send" style="background:#2e6b46;color:#fff;border:0;padding:6px 10px;border-radius:4px;cursor:pointer">Send</button>
    </div>
    <div style="padding:0 8px 8px;display:flex;gap:5px">
      <button id="dev-chat-analyze" style="flex:1;background:#23425c;color:#fff;border:0;padding:5px;border-radius:4px;cursor:pointer">Auto-analyze</button>
      <button id="dev-chat-save" style="flex:1;background:#5a4a1e;color:#fff;border:0;padding:5px;border-radius:4px;cursor:pointer">Save file</button>
      <button id="dev-chat-clear" style="flex:1;background:#4a2626;color:#fff;border:0;padding:5px;border-radius:4px;cursor:pointer">Clear</button>
    </div>`
  document.body.appendChild(panel)
  logEl = panel.querySelector('#dev-chat-log')
  inputEl = panel.querySelector('#dev-chat-input')
  panel.querySelector('#dev-chat-send').onclick = send
  panel.querySelector('#dev-chat-analyze').onclick = analyze
  panel.querySelector('#dev-chat-save').onclick = save
  panel.querySelector('#dev-chat-clear').onclick = () => { messages = []; persist(); render(); toastSaved('Chat cleared') }
  inputEl.addEventListener('keydown', (e) => { if (e.key === 'Enter') { e.preventDefault(); send() } if (e.key === 'Escape') toggle(false) })
  const cnt = panel.querySelector('#dev-chat-count')
  const upd = () => { if (cnt) cnt.textContent = messages.length ? `${messages.length} msg` : '' }
  const origPost = post
  render()
  // keep count fresh
  setInterval(upd, 1000)
  return panel
}

// ---- init -------------------------------------------------------------------
load()
if (document.body) makePanel(); else addEventListener('DOMContentLoaded', makePanel)
addEventListener('keydown', (e) => {
  if (e.code !== 'F2') return
  e.preventDefault(); e.stopImmediatePropagation()
  toggle()
}, true)

const api = {
  version: '1.0.0',
  toggle, post, send, save, analyze, fileText,
  issue: (text, meta = {}) => post({ who: 'human', kind: 'issue', text, ...meta }),
  agent: (text, meta = {}) => post({ who: 'agent', kind: 'note', text, ...meta }),
  list: () => messages.slice(),
  issues: () => messages.filter(m => m.kind === 'issue'),
  clear: () => { messages = []; persist(); render() }
}
window.__devChat = api
export default api
